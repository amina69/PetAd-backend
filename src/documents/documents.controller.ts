import {
  Controller,
  Delete,
  Get,
  Header,
  Param,
  Query,
  Req,
  StreamableFile,
  UseGuards,
} from '@nestjs/common';
import {
  ApiBearerAuth,
  ApiOperation,
  ApiParam,
  ApiResponse,
  ApiTags,
} from '@nestjs/swagger';
import type { Request } from 'express';
import { JwtAuthGuard } from '../auth/guards/jwt-auth.guard';
import { Public } from '../auth/decorators/public.decorator';
import { CheckPolicy } from '../common/policies/check-policy.decorator';
import { PolicyAction, PolicySubject } from '../common/policies/policy.types';
import { DocumentsService } from './documents.service';
import {
  DownloadUrlQueryDto,
  ListDocumentsDto,
} from './dto/documents-query.dto';

interface AuthRequest extends Request {
  user?: {
    userId?: string;
    sub?: string;
    role?: string;
  };
}

@ApiTags('Documents')
@ApiBearerAuth('JWT-auth')
@Controller('documents')
@UseGuards(JwtAuthGuard)
export class DocumentsController {
  constructor(private readonly documentsService: DocumentsService) {}

  @Get()
  @ApiOperation({
    summary: 'List documents for an entity',
    description:
      'Returns the non-deleted documents attached to an adoption, custody, ' +
      'dispute, message or profile. Callers who cannot access the entity get 404.',
  })
  @ApiResponse({ status: 200, description: 'Documents found' })
  @ApiResponse({ status: 404, description: 'Entity not found' })
  listDocuments(@Query() query: ListDocumentsDto, @Req() req: AuthRequest) {
    return this.documentsService.list(query.entityType, query.entityId, {
      userId: this.userId(req),
      role: req.user?.role ?? 'USER',
    });
  }

  @Get(':id')
  @CheckPolicy(PolicyAction.READ, PolicySubject.DOCUMENT)
  @ApiOperation({
    summary: 'Get a document',
    description:
      'Readable by its uploader, the parties of the related adoption or ' +
      'message conversation, the profile owner, or an admin. ' +
      'Any other caller gets 404 so the document is not disclosed.',
  })
  @ApiParam({ name: 'id', description: 'Document ID' })
  @ApiResponse({ status: 200, description: 'Document found' })
  @ApiResponse({ status: 401, description: 'Unauthorized' })
  @ApiResponse({ status: 404, description: 'Document not found' })
  getDocument(@Param('id') id: string) {
    return this.documentsService.findOne(id);
  }

  @Get(':id/download-url')
  @CheckPolicy(PolicyAction.READ, PolicySubject.DOCUMENT)
  @Header('Cache-Control', 'no-store, max-age=0')
  @ApiOperation({
    summary: 'Create a short-lived signed download URL',
    description:
      'Generates a fresh URL valid for 60-300 seconds (default 120). The URL ' +
      'must never be cached; it stops working once it expires.',
  })
  @ApiResponse({ status: 200, description: 'Signed URL created' })
  @ApiResponse({ status: 404, description: 'Document not found' })
  createDownloadUrl(
    @Param('id') id: string,
    @Query() query: DownloadUrlQueryDto,
    @Req() req: AuthRequest,
  ) {
    return this.documentsService.createDownloadUrl(
      id,
      this.baseUrl(req),
      query.expiresIn,
    );
  }

  @Public()
  @Get(':id/download')
  @Header('Cache-Control', 'no-store, max-age=0')
  @ApiOperation({
    summary: 'Download a document using a signed link',
    description:
      'Validates the signature and expiry generated by /download-url. ' +
      'Expired or tampered links are rejected.',
  })
  @ApiResponse({ status: 200, description: 'Document content' })
  @ApiResponse({ status: 403, description: 'Invalid signature' })
  @ApiResponse({ status: 410, description: 'Download link has expired' })
  async downloadDocument(
    @Param('id') id: string,
    @Query('expires') expires: string | undefined,
    @Query('sig') sig: string | undefined,
  ): Promise<StreamableFile> {
    const { document, body } = await this.documentsService.downloadSigned(
      id,
      expires,
      sig,
    );

    const safeName = document.fileName.replace(/["\r\n]/g, '_');

    return new StreamableFile(body, {
      type: document.mimeType || 'application/octet-stream',
      disposition: `attachment; filename="${safeName}"`,
    });
  }

  @Delete(':id')
  @CheckPolicy(PolicyAction.DELETE, PolicySubject.DOCUMENT)
  @ApiOperation({
    summary: 'Soft-delete a document',
    description:
      'Only the uploader (or an admin) can delete. Returns 409 when the ' +
      'document is attached to an adoption still under review or to an open dispute.',
  })
  @ApiResponse({ status: 200, description: 'Document deleted' })
  @ApiResponse({ status: 404, description: 'Document not found' })
  @ApiResponse({
    status: 409,
    description: 'Document is attached to a live record',
  })
  deleteDocument(@Param('id') id: string) {
    return this.documentsService.remove(id);
  }

  private userId(req: AuthRequest): string {
    return (req.user?.userId ?? req.user?.sub) as string;
  }

  private baseUrl(req: AuthRequest): string {
    const forwardedProto = req.get('x-forwarded-proto')?.split(',')[0]?.trim();
    const protocol = forwardedProto || req.protocol;
    return `${protocol}://${req.get('host')}`;
  }
}
